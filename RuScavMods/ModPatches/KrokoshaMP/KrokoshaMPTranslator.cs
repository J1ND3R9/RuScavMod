    [HarmonyPatch]
    internal static class MPLangGetPatch
    {
        [HarmonyPatch(typeof(Lang), nameof(Lang.Get))]
        [HarmonyPrefix]
        static bool Prefix(ref string __result, in string key)
        {
            string locale = Locale.currentLangName ?? "EN";
            bool isAnyRU = locale.ToLower().Contains("ru");

            if (!isAnyRU || locale == "RU-expand") return true;
            string newKey = $"casualtiestogether_{key}";
            if (KrokoshaMPTranslator.TranslationDictionary.TryGetValue(newKey, out string value))
            {
                __result = value;
                return false;
            }
            return true;
        }
    }

